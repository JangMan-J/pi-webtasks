// Runs inside each isolated treatment. No provider or paid research requests.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {loadExtensions} from '/opt/pi/dist/core/extensions/loader.js';
import {loadSkills} from '/opt/pi/dist/core/skills.js';
import {buildSystemPromptSections} from '/opt/pi/dist/core/system-prompt.js';
const arm=process.env.BENCH_ARM;
const paths=arm==='E'?['/opt/extension/src/index.ts']:[];
const loaded=await loadExtensions(paths,'/work');assert.deepEqual(loaded.errors,[]);
const tools=loaded.extensions.flatMap(e=>[...e.tools.values()].map(t=>t.definition));
assert.equal(tools.length,arm==='E'?9:0);
const s=loadSkills({cwd:'/work',agentDir:'/work/home/.pi/agent',includeDefaults:false,skillPaths:[arm==='C'?'/opt/resources':'/opt/resources/find-docs']});
assert.equal(s.skills.length,arm==='E'?1:11);assert.deepEqual(s.diagnostics,[]);
assert(s.skills.some(s=>s.name==='find-docs'));
assert.equal(fs.existsSync('/opt/extension'),arm==='E');
assert.equal(fs.existsSync('/opt/cli'),arm==='C');
assert.equal(fs.existsSync('/opt/cli-source'),arm==='C');
assert.equal(fs.existsSync('/home/jangpi'),false);
assert.equal(fs.existsSync('/opt/resources/parallel-web-search'),arm==='C');
assert.equal(fs.existsSync('/opt/bench/gold.json'),false);
assert.equal(fs.existsSync('/opt/bench/manifest.json'),false);
assert.equal(fs.existsSync('/opt/bench/gateway.ts'),false);
assert.throws(()=>fs.writeFileSync('/opt/resources/find-docs/probe','x'));
fs.writeFileSync('/work/writable','ok');
if(arm==='C')assert(fs.existsSync('/opt/resources/parallel-web-search/../find-docs/SKILL.md'));
const prompt=buildSystemPromptSections({cwd:'/work',selectedTools:['read','bash','edit','write',...tools.map(t=>t.name)],toolSnippets:Object.fromEntries(tools.map(t=>[t.name,t.promptSnippet])),toolGuidelines:Object.fromEntries(tools.map(t=>[t.name,t.promptGuidelines])),skills:s.skills,appendSystemPrompt:'BENCH-PREFLIGHT-APPEND'});
if(arm==='E')for(const tool of tools)for(const rule of tool.promptGuidelines??[])assert(prompt.rules.includes(rule));
assert(prompt.addendum.includes('BENCH-PREFLIGHT-APPEND'));
const ctx=JSON.parse(fs.readFileSync('/opt/ctx7/node_modules/ctx7/package.json'));assert.equal(ctx.version,'0.5.11');
const npx=execFileSync('npx',['ctx7@latest','--version'],{encoding:'utf8'}).trim();assert.match(npx,/0\.5\.11/);
console.log(JSON.stringify({arm,passed:true,tools:tools.map(t=>t.name),skills:s.skills.map(s=>s.name),context7:ctx.version,network:'unrestricted (same runtime as live smoke)',promptSections:Object.keys(prompt)}));
